// Command gld-kilngen-go emits Go structs from the Kiln JSON Schema subset.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"unicode"
)

type typ struct {
	name   string
	kind   string
	elem   *typ
	fields []field
}

type field struct {
	goName   string
	wireName string
	typ      *typ
	optional bool
}

type unit struct {
	name string
	body *typ
}

func main() {
	fs := flag.NewFlagSet("gld-kilngen-go", flag.ExitOnError)
	schemaPath := fs.String("schema", "", "JSON Schema file")
	outDir := fs.String("out", "", "directory for the generated Go file")
	_ = fs.Parse(os.Args[1:])
	if *schemaPath == "" || *outDir == "" {
		fmt.Fprintln(os.Stderr, "usage: gld-kilngen-go --schema file.json --out dir")
		os.Exit(2)
	}
	raw, err := os.ReadFile(*schemaPath)
	if err != nil {
		fail(err)
	}
	file, name, err := generate(raw)
	if err != nil {
		fail(err)
	}
	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		fail(err)
	}
	path := filepath.Join(*outDir, strings.ToLower(name)+".go")
	if err := os.WriteFile(path, file, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func generate(raw []byte) ([]byte, string, error) {
	_, root, err := objectFields(raw)
	if err != nil {
		return nil, "", err
	}
	defs := map[string]json.RawMessage{}
	var defOrder []string
	if blob, ok := root["$defs"]; ok {
		defOrder, defs, err = objectFields(blob)
		if err != nil {
			return nil, "", err
		}
	}
	titles := map[string]string{}
	for _, key := range defOrder {
		title := objectTitle(defs[key])
		if title == "" {
			title = exportName(key)
		}
		titles[key] = title
	}
	var units []unit
	for _, key := range defOrder {
		body, err := compile(defs[key], defs, titles)
		if err != nil {
			return nil, "", err
		}
		body.name = titles[key]
		if body.kind == "struct" || body.kind == "dict" {
			units = append(units, unit{name: titles[key], body: body})
		}
	}
	rootType, err := compile(raw, defs, titles)
	if err != nil {
		return nil, "", err
	}
	title := objectTitle(raw)
	if title == "" {
		title = "Value"
	}
	rootType.name = title
	seen := map[string]bool{}
	for _, u := range units {
		seen[u.name] = true
	}
	if !seen[title] {
		units = append(units, unit{name: title, body: rootType})
	}
	var b strings.Builder
	b.WriteString("// Code generated by gld-kilngen-go. DO NOT EDIT.\n\n")
	b.WriteString("package generated\n\n")
	needSort := false
	for _, u := range units {
		if usesDict(u.body) {
			needSort = true
		}
	}
	b.WriteString("import (\n")
	if needSort {
		b.WriteString("\t\"sort\"\n\n")
	}
	b.WriteString("\t\"github.com/leo-gan/gld-kiln-go\"\n)\n\n")
	for _, u := range units {
		if err := emitType(&b, u); err != nil {
			return nil, "", err
		}
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, "", fmt.Errorf("format: %w\n%s", err, b.String())
	}
	return src, title, nil
}

func usesDict(t *typ) bool {
	if t == nil {
		return false
	}
	if t.kind == "dict" {
		return true
	}
	if usesDict(t.elem) {
		return true
	}
	for _, f := range t.fields {
		if usesDict(f.typ) {
			return true
		}
	}
	return false
}

func compile(raw json.RawMessage, defs map[string]json.RawMessage, titles map[string]string) (*typ, error) {
	_, fields, err := objectFields(raw)
	if err != nil {
		return nil, err
	}
	if ref, ok := fields["$ref"]; ok {
		name, err := jsonString(ref)
		if err != nil {
			return nil, err
		}
		const prefix = "#/$defs/"
		if !strings.HasPrefix(name, prefix) || strings.Contains(name[len(prefix):], "/") {
			return nil, fmt.Errorf("kiln: $ref %s", name)
		}
		key := name[len(prefix):]
		title, ok := titles[key]
		if !ok {
			return nil, fmt.Errorf("kiln: unknown $ref %s", key)
		}
		return &typ{kind: "ref", name: title}, nil
	}
	kind, err := jsonString(fields["type"])
	if err != nil {
		return nil, err
	}
	switch kind {
	case "boolean":
		return &typ{kind: "bool"}, nil
	case "integer":
		format, _ := jsonString(fields["format"])
		wire, err := intWire(format)
		if err != nil {
			return nil, err
		}
		return &typ{kind: wire}, nil
	case "number":
		format, _ := jsonString(fields["format"])
		if format == "" || format == "double" {
			return &typ{kind: "f64"}, nil
		}
		if format == "float" {
			return &typ{kind: "f32"}, nil
		}
		return nil, fmt.Errorf("kiln: number format %s", format)
	case "string":
		format, _ := jsonString(fields["format"])
		if format == "binary" {
			return &typ{kind: "bytes"}, nil
		}
		if format != "" {
			return nil, fmt.Errorf("kiln: string format %s", format)
		}
		return &typ{kind: "str"}, nil
	case "array":
		items, ok := fields["items"]
		if !ok {
			return nil, fmt.Errorf("kiln: array needs items")
		}
		elem, err := compile(items, defs, titles)
		if err != nil {
			return nil, err
		}
		return &typ{kind: "list", elem: elem}, nil
	case "object":
		if _, ok := fields["properties"]; !ok {
			add, ok := fields["additionalProperties"]
			if !ok {
				return &typ{kind: "struct"}, nil
			}
			text := strings.TrimSpace(string(add))
			if text == "true" || text == "false" {
				return nil, fmt.Errorf("kiln: additionalProperties is not a value schema")
			}
			elem, err := compile(add, defs, titles)
			if err != nil {
				return nil, err
			}
			return &typ{kind: "dict", elem: elem}, nil
		}
		propKeys, props, err := objectFields(fields["properties"])
		if err != nil {
			return nil, err
		}
		required, all, err := requiredSet(fields["required"])
		if err != nil {
			return nil, err
		}
		out := &typ{kind: "struct"}
		for _, wire := range propKeys {
			ft, err := compile(props[wire], defs, titles)
			if err != nil {
				return nil, err
			}
			out.fields = append(out.fields, field{
				goName:   exportName(wire),
				wireName: wire,
				typ:      ft,
				optional: !all && !required[wire],
			})
		}
		return out, nil
	default:
		return nil, fmt.Errorf("kiln: unsupported schema type %q", kind)
	}
}

func intWire(format string) (string, error) {
	switch format {
	case "":
		return "int", nil
	case "int8":
		return "i8", nil
	case "int16":
		return "i16", nil
	case "int32":
		return "i32", nil
	case "int64":
		return "i64", nil
	case "uint8":
		return "u8", nil
	case "uint16":
		return "u16", nil
	case "uint32":
		return "u32", nil
	case "uint64":
		return "u64", nil
	default:
		return "", fmt.Errorf("kiln: integer format %s", format)
	}
}

func emitType(b *strings.Builder, u unit) error {
	switch u.body.kind {
	case "struct":
		fmt.Fprintf(b, "type %s struct {\n", u.name)
		for _, f := range u.body.fields {
			fmt.Fprintf(b, "\t%s %s\n", f.goName, goType(f.typ, f.optional))
		}
		b.WriteString("}\n\n")
		emitStructMethods(b, u.name, u.body)
	case "dict":
		fmt.Fprintf(b, "type %s map[string]%s\n\n", u.name, goType(u.body.elem, false))
		emitDictMethods(b, u.name, u.body.elem)
	default:
		return fmt.Errorf("kiln: cannot emit %s", u.body.kind)
	}
	return nil
}

func emitStructMethods(b *strings.Builder, name string, t *typ) {
	fmt.Fprintf(b, "func (v %s) EncodedSize() int {\n\tn := 0\n", name)
	for _, f := range t.fields {
		b.WriteString(sizeStmt("v."+f.goName, f.typ, f.optional, 1))
	}
	b.WriteString("\treturn n\n}\n\n")
	fmt.Fprintf(b, "func (v %s) Encode() ([]byte, error) {\n\treturn v.appendEnc(nil)\n}\n\n", name)
	fmt.Fprintf(b, "func (v %s) appendEnc(dst []byte) ([]byte, error) {\n\tvar err error\n", name)
	for _, f := range t.fields {
		b.WriteString(encodeStmt("v."+f.goName, f.typ, f.optional))
	}
	b.WriteString("\treturn dst, nil\n}\n\n")
	fmt.Fprintf(b, "func Decode%s(buf []byte) (%s, error) {\n", name, name)
	fmt.Fprintf(b, "\tv, rest, err := decode%s(buf)\n", name)
	b.WriteString("\tif err != nil {\n\t\treturn v, err\n\t}\n")
	b.WriteString("\tif len(rest) != 0 {\n\t\treturn v, kiln.Fail(\"TRAILING\")\n\t}\n")
	b.WriteString("\treturn v, nil\n}\n\n")
	fmt.Fprintf(b, "func decode%s(buf []byte) (%s, []byte, error) {\n\tvar v %s\n\tvar err error\n", name, name, name)
	for _, f := range t.fields {
		b.WriteString(decodeStmt("v."+f.goName, f.typ, f.optional))
	}
	b.WriteString("\treturn v, buf, nil\n}\n\n")
}

func emitDictMethods(b *strings.Builder, name string, elem *typ) {
	fmt.Fprintf(b, "func (v %s) EncodedSize() int {\n", name)
	b.WriteString("\tkeys := dictKeys(v)\n\tn := 4\n")
	b.WriteString("\tfor _, k := range keys {\n")
	b.WriteString("\t\tn += 4 + len(k)\n")
	b.WriteString(sizeStmt("v[k]", elem, false, 2))
	b.WriteString("\t}\n\treturn n\n}\n\n")
	fmt.Fprintf(b, "func (v %s) Encode() ([]byte, error) {\n", name)
	b.WriteString("\tkeys := dictKeys(v)\n\tdst := make([]byte, 0, v.EncodedSize())\n")
	b.WriteString("\tdst = kiln.PutU32(dst, uint32(len(keys)))\n")
	b.WriteString("\tvar err error\n\tfor _, k := range keys {\n")
	b.WriteString("\t\tdst, err = kiln.PutString(dst, k)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
	b.WriteString(encodeStmt("v[k]", elem, false))
	b.WriteString("\t}\n\treturn dst, nil\n}\n\n")
	fmt.Fprintf(b, "func Decode%s(buf []byte) (%s, error) {\n", name, name)
	b.WriteString("\tv, rest, err := decode" + name + "(buf)\n")
	b.WriteString("\tif err != nil {\n\t\treturn v, err\n\t}\n")
	b.WriteString("\tif len(rest) != 0 {\n\t\treturn v, kiln.Fail(\"TRAILING\")\n\t}\n\treturn v, nil\n}\n\n")
	fmt.Fprintf(b, "func decode%s(buf []byte) (%s, []byte, error) {\n", name, name)
	b.WriteString("\tif len(buf) < 4 {\n\t\treturn nil, buf, kiln.Fail(\"EOF\")\n\t}\n")
	b.WriteString("\tn, rest, err := kiln.TakeU32(buf)\n\tif err != nil {\n\t\treturn nil, buf, err\n\t}\n")
	fmt.Fprintf(b, "\tif err = kiln.CheckCount(len(rest), n, %d, 0); err != nil {\n\t\treturn nil, rest, err\n\t}\n", 4+minWire(elem))
	fmt.Fprintf(b, "\tout := make(%s, n)\n\tvar prev string\n\tvar have bool\n", name)
	b.WriteString("\tbuf = rest\n\tfor i := uint32(0); i < n; i++ {\n")
	b.WriteString("\t\tvar k string\n\t\tk, buf, err = kiln.TakeString(buf, kiln.Options{})\n")
	b.WriteString("\t\tif err != nil {\n\t\t\treturn nil, buf, err\n\t\t}\n")
	b.WriteString("\t\tif have && k <= prev {\n\t\t\treturn nil, buf, kiln.Fail(\"TYPE\")\n\t\t}\n")
	b.WriteString("\t\tprev, have = k, true\n")
	b.WriteString(decodeStmt("out[k]", elem, false))
	b.WriteString("\t}\n\treturn out, buf, nil\n}\n\n")
	b.WriteString("func dictKeys[M ~map[string]V, V any](m M) []string {\n")
	b.WriteString("\tkeys := make([]string, 0, len(m))\n\tfor k := range m {\n\t\tkeys = append(keys, k)\n\t}\n")
	b.WriteString("\tsort.Strings(keys)\n\treturn keys\n}\n\n")
}

func sizeStmt(expr string, t *typ, optional bool, tabs int) string {
	pad := strings.Repeat("\t", tabs)
	if optional {
		inner := strings.TrimPrefix(sizeStmt("(*"+expr+")", innerOf(t), false, tabs+1), pad+"\t")
		return pad + "if " + expr + " == nil {\n" + pad + "\tn += 1\n" + pad + "} else {\n" + pad + "\tn += 1\n" + pad + "\t" + inner + pad + "}\n"
	}
	switch t.kind {
	case "bool", "i8", "u8":
		return pad + "n += 1\n"
	case "i16", "u16":
		return pad + "n += 2\n"
	case "i32", "u32", "f32":
		return pad + "n += 4\n"
	case "i64", "int", "u64", "uint", "f64":
		return pad + "n += 8\n"
	case "str":
		return pad + "n += kiln.SizeString(" + expr + ")\n"
	case "bytes":
		return pad + "n += kiln.SizeBytes(" + expr + ")\n"
	case "ref", "struct":
		return pad + "n += " + expr + ".EncodedSize()\n"
	case "list":
		return pad + "n += 4\n" + pad + "for _, item := range " + expr + " {\n" + sizeStmt("item", t.elem, false, tabs+1) + pad + "}\n"
	default:
		return pad + "n += 0\n"
	}
}

func innerOf(t *typ) *typ {
	if t.kind == "ref" {
		return t
	}
	return t
}

func encodeStmt(expr string, t *typ, optional bool) string {
	if optional {
		inner := encodeStmt("(*"+expr+")", t, false)
		return "\tif " + expr + " == nil {\n\t\tdst = append(dst, 0)\n\t} else {\n\t\tdst = append(dst, 1)\n" + indent(inner) + "\t}\n"
	}
	switch t.kind {
	case "bool":
		return "\tdst = kiln.PutBool(dst, " + expr + ")\n"
	case "i8":
		return "\tdst = kiln.PutI8(dst, " + expr + ")\n"
	case "u8":
		return "\tdst = kiln.PutU8(dst, " + expr + ")\n"
	case "i16":
		return "\tdst = kiln.PutI16(dst, " + expr + ")\n"
	case "u16":
		return "\tdst = kiln.PutU16(dst, " + expr + ")\n"
	case "i32":
		return "\tdst = kiln.PutI32(dst, " + expr + ")\n"
	case "u32":
		return "\tdst = kiln.PutU32(dst, " + expr + ")\n"
	case "i64", "int":
		return "\tdst = kiln.PutI64(dst, " + expr + ")\n"
	case "u64", "uint":
		return "\tdst = kiln.PutU64(dst, " + expr + ")\n"
	case "f32":
		return "\tdst = kiln.PutF32(dst, " + expr + ")\n"
	case "f64":
		return "\tdst = kiln.PutF64(dst, " + expr + ")\n"
	case "str":
		return "\tdst, err = kiln.PutString(dst, " + expr + ")\n\tif err != nil {\n\t\treturn nil, err\n\t}\n"
	case "bytes":
		return "\tdst, err = kiln.PutBytes(dst, " + expr + ")\n\tif err != nil {\n\t\treturn nil, err\n\t}\n"
	case "ref", "struct":
		return "\tdst, err = " + expr + ".appendEnc(dst)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n"
	case "list":
		return "\tif len(" + expr + ") > 0xFFFFFFFF {\n\t\treturn nil, kiln.Fail(\"LIMIT\")\n\t}\n" +
			"\tdst = kiln.PutU32(dst, uint32(len(" + expr + ")))\n" +
			"\tfor _, item := range " + expr + " {\n" + indent(encodeStmt("item", t.elem, false)) + "\t}\n"
	default:
		return "\treturn nil, kiln.Fail(\"TYPE\")\n"
	}
}

func decodeStmt(lhs string, t *typ, optional bool) string {
	if optional {
		return decodeOpt(lhs, t)
	}
	switch t.kind {
	case "bool":
		return assignTake(lhs, "kiln.TakeBool(buf)")
	case "i8":
		return assignTake(lhs, "kiln.TakeI8(buf)")
	case "u8":
		return assignTake(lhs, "kiln.TakeU8(buf)")
	case "i16":
		return assignTake(lhs, "kiln.TakeI16(buf)")
	case "u16":
		return assignTake(lhs, "kiln.TakeU16(buf)")
	case "i32":
		return assignTake(lhs, "kiln.TakeI32(buf)")
	case "u32":
		return assignTake(lhs, "kiln.TakeU32(buf)")
	case "i64", "int":
		return assignTake(lhs, "kiln.TakeI64(buf)")
	case "u64", "uint":
		return assignTake(lhs, "kiln.TakeU64(buf)")
	case "f32":
		return assignTake(lhs, "kiln.TakeF32(buf)")
	case "f64":
		return assignTake(lhs, "kiln.TakeF64(buf)")
	case "str":
		return assignTake(lhs, "kiln.TakeString(buf, kiln.Options{})")
	case "bytes":
		return assignTake(lhs, "kiln.TakeBytes(buf, kiln.Options{})")
	case "ref":
		return "\t" + lhs + ", buf, err = decode" + t.name + "(buf)\n\tif err != nil {\n\t\treturn v, buf, err\n\t}\n"
	case "list":
		return decodeList(lhs, t.elem)
	default:
		return "\treturn v, buf, kiln.Fail(\"TYPE\")\n"
	}
}

func decodeOpt(lhs string, t *typ) string {
	switch t.kind {
	case "str":
		return assignTake(lhs, "kiln.TakeOptString(buf, kiln.Options{})")
	default:
		inner := goType(t, false)
		body := "\tif len(buf) < 1 {\n\t\treturn v, buf, kiln.Fail(\"EOF\")\n\t}\n"
		body += "\tswitch buf[0] {\n\tcase 0:\n\t\tbuf = buf[1:]\n\tcase 1:\n\t\tvar inner " + inner + "\n"
		body += strings.ReplaceAll(decodeStmt("inner", t, false), "return v,", "return v,")
		body += "\t\t" + lhs + " = &inner\n\tdefault:\n\t\treturn v, buf, kiln.Fail(\"TYPE\")\n\t}\n"
		return body
	}
}

func decodeList(lhs string, elem *typ) string {
	goElem := goType(elem, false)
	body := "\tif len(buf) < 4 {\n\t\treturn v, buf, kiln.Fail(\"EOF\")\n\t}\n"
	body += "\tvar n uint32\n\tn, buf, err = kiln.TakeU32(buf)\n\tif err != nil {\n\t\treturn v, buf, err\n\t}\n"
	body += fmt.Sprintf("\tif err = kiln.CheckCount(len(buf), n, %d, 0); err != nil {\n\t\treturn v, buf, err\n\t}\n", minWire(elem))
	body += "\t" + lhs + " = make([]" + goElem + ", n)\n"
	body += "\tfor i := range " + lhs + " {\n"
	body += indent(decodeStmt(lhs+"[i]", elem, false))
	body += "\t}\n"
	return body
}

func assignTake(lhs, call string) string {
	return "\t" + lhs + ", buf, err = " + call + "\n\tif err != nil {\n\t\treturn v, buf, err\n\t}\n"
}

func indent(s string) string {
	var b strings.Builder
	for _, line := range strings.Split(s, "\n") {
		if line == "" {
			continue
		}
		b.WriteString("\t")
		b.WriteString(line)
		b.WriteString("\n")
	}
	return b.String()
}

func goType(t *typ, optional bool) string {
	var base string
	switch t.kind {
	case "bool":
		base = "bool"
	case "i8":
		base = "int8"
	case "i16":
		base = "int16"
	case "i32":
		base = "int32"
	case "i64", "int":
		base = "int64"
	case "u8":
		base = "uint8"
	case "u16":
		base = "uint16"
	case "u32":
		base = "uint32"
	case "u64", "uint":
		base = "uint64"
	case "f32":
		base = "float32"
	case "f64":
		base = "float64"
	case "str":
		base = "string"
	case "bytes":
		base = "[]byte"
	case "list":
		base = "[]" + goType(t.elem, false)
	case "dict":
		base = "map[string]" + goType(t.elem, false)
	case "ref":
		base = t.name
	default:
		base = "struct{}"
	}
	if optional {
		if strings.HasPrefix(base, "[]") || strings.HasPrefix(base, "map[") {
			return "*" + base
		}
		return "*" + base
	}
	return base
}

func minWire(t *typ) int {
	switch t.kind {
	case "bool", "i8", "u8":
		return 1
	case "i16", "u16":
		return 2
	case "i32", "u32", "f32":
		return 4
	case "i64", "int", "u64", "uint", "f64":
		return 8
	case "str", "bytes", "list", "dict":
		return 4
	case "ref", "struct":
		n := 0
		for _, f := range t.fields {
			if f.optional {
				n++
				continue
			}
			n += minWire(f.typ)
		}
		return n
	default:
		return 1
	}
}

func objectTitle(raw json.RawMessage) string {
	_, fields, err := objectFields(raw)
	if err != nil {
		return ""
	}
	s, err := jsonString(fields["title"])
	if err != nil {
		return ""
	}
	return exportName(s)
}

func requiredSet(raw json.RawMessage) (map[string]bool, bool, error) {
	if len(bytes.TrimSpace(raw)) == 0 {
		return nil, true, nil
	}
	var names []string
	if err := json.Unmarshal(raw, &names); err != nil {
		return nil, false, err
	}
	set := make(map[string]bool, len(names))
	for _, name := range names {
		set[name] = true
	}
	return set, false, nil
}

func objectFields(raw json.RawMessage) ([]string, map[string]json.RawMessage, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	tok, err := dec.Token()
	if err != nil {
		return nil, nil, err
	}
	if d, ok := tok.(json.Delim); !ok || d != '{' {
		return nil, nil, fmt.Errorf("kiln: schema value is not an object")
	}
	var keys []string
	fields := map[string]json.RawMessage{}
	for dec.More() {
		tok, err = dec.Token()
		if err != nil {
			return nil, nil, err
		}
		key, ok := tok.(string)
		if !ok {
			return nil, nil, fmt.Errorf("kiln: object key")
		}
		var body json.RawMessage
		if err := dec.Decode(&body); err != nil {
			return nil, nil, err
		}
		keys = append(keys, key)
		fields[key] = body
	}
	return keys, fields, nil
}

func jsonString(raw json.RawMessage) (string, error) {
	if len(bytes.TrimSpace(raw)) == 0 {
		return "", fmt.Errorf("missing")
	}
	var s string
	if err := json.Unmarshal(raw, &s); err != nil {
		return "", err
	}
	return s, nil
}

func exportName(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool {
		return r == '_' || r == '-' || r == ' '
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	name := b.String()
	if name == "" {
		return "Field"
	}
	if name[0] >= '0' && name[0] <= '9' {
		return "N" + name
	}
	return name
}
